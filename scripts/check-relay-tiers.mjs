import { readFileSync } from "node:fs";
import vm from "node:vm";
import assert from "node:assert/strict";
const code = readFileSync(new URL("../relay-exchange-engine.js", import.meta.url), "utf8");
const context = { module: { exports: {} } };
vm.runInNewContext(code, context);
const engine = context.module.exports;
const purchase = { id: "purchase-1", item: "Retro High Trainers", detail: "White / Grey / UK 7", merchant: "North & Co.", price: 129.99, demo: true };
const candidate = { product: "Retro High Trainers", variation: "White / Grey / UK 8", store: "North & Co.", priceMinor: 12999, sku: "DEMO-RETRO-UK8", quantity: 2, fixture: true };
const requested = engine.createReturnOnly({purchase,id:"request-1234"});
assert.equal(requested.returnStatus,"RETURN_REQUESTED");
assert.throws(()=>engine.quote({purchase,candidate,reason:"size",existing:[requested]}),/return/);
let received=requested;
for(let i=0;i<3;i++)received=engine.advanceReturn(received);
assert.equal(received.returnStatus,"RETURN_RECEIVED");
const quote=engine.quote({purchase,candidate,reason:"size",existing:[received]});
assert.equal(quote.differenceMinor,0);
const exchange=engine.createExchange({purchase,candidate,reason:"size",existing:[received],id:"exchange-1234"});
assert.equal(exchange.returnStatus,"RETURN_RECEIVED");
assert.equal(exchange.returnRequestId,received.returnRequestId,"Re-use the received return, do not create a duplicate");
const finished=engine.advanceReturn(received);
assert.equal(finished.returnStatus,"RETURN_COMPLETED");
assert.equal(finished.status,"SIMULATED_STANDARD_REFUND_AFTER_RETURN");
assert.equal(finished.ledger[0].type,"STANDARD_REFUND_AFTER_RETURN");
const exchangedReturn=engine.advanceReturn(received,undefined,{exchangeAlreadyIssued:true});
assert.equal(exchangedReturn.status,"RETURN_COMPLETED_WITH_EXCHANGE");
assert.equal(exchangedReturn.ledger.length,0,"An exchanged return must not also receive a standard refund");
assert.throws(()=>engine.quote({purchase,candidate,reason:"size",existing:[finished]}),/return/,"Cannot refund then exchange twice");
console.log("PASS Free return-first exchange, no duplicate return, standard refund after completion");
