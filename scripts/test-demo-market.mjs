// The investor demo of the Market: only with ?demo=1, clearly labelled, never talks to Relay's server.
import assert from "node:assert/strict";
import { createRequire } from "node:module"; import { createServer } from "node:http"; import { readFile } from "node:fs/promises"; import { resolve, extname } from "node:path";
const require = createRequire(import.meta.url); const { chromium } = require("playwright");
const server = createServer(async (req, res) => { try { const p = resolve(".", "." + new URL(req.url, "http://x").pathname.replace(/\/$/, "/index.html")); res.setHeader("Content-Type", extname(p) === ".js" ? "text/javascript" : extname(p) === ".png" ? "image/png" : "text/html"); res.end(await readFile(p)); } catch { res.statusCode = 404; res.end(); } });
await new Promise(r => server.listen(0, "127.0.0.1", r)); const origin = "http://127.0.0.1:" + server.address().port;
const browser = await chromium.launch();
const ctx = await browser.newContext({ viewport: { width: 1280, height: 900 } });
const resaleCalls = [];
await ctx.route("https://**/*", route => { const u = new URL(route.request().url()); if (/resale/.test(u.pathname)) resaleCalls.push(u.pathname);
  if (route.request().method() === "OPTIONS") return route.fulfill({ status: 204, headers: { "access-control-allow-origin": "*", "access-control-allow-headers": "*", "access-control-allow-methods": "*" } });
  return u.pathname.startsWith("/relay/") ? route.fulfill({ status: 200, contentType: "application/json", headers: { "access-control-allow-origin": "*" }, body: JSON.stringify({ listings: [] }) }) : route.abort(); });
const page = await ctx.newPage(); const errors = []; page.on("pageerror", e => errors.push(String(e)));
await page.addInitScript(() => localStorage.setItem("relay.session.v1", JSON.stringify({ token: "S".repeat(43), email: "c@example.com" })));
await page.goto(origin + "/index.html?demo=1"); await page.waitForTimeout(800);
await page.evaluate(() => window.go("market"));
const m = page.locator("#marketPage");
await m.getByText("made-up members and listings", { exact: false }).waitFor();
assert.equal((await m.locator(".rl-po").first().innerText()).includes("Near you"), true, "listings near the shopper's area come first");
await m.getByText("Receipt checked by Relay", { exact: false }).first().waitFor();
await m.locator(".rl-po", { hasText: "Waterproof Rain Shell" }).getByRole("button", { name: "I'd like this" }).click();
await page.getByText("Yes, it is!", { exact: false }).waitFor({ timeout: 5000 });
await page.locator(".rl-sheet input").fill("call me on 07700 900123");
await page.locator(".rl-sheet").getByRole("button", { name: "Send" }).click();
await page.getByText("Relay keeps phone numbers and emails out of chats", { exact: false }).waitFor();
await page.locator(".rl-sheet").getByRole("button", { name: "Close" }).click();
await m.getByRole("button", { name: "Sell" }).click();
await m.locator(".rl-po", { hasText: "Linen Shirt" }).getByRole("button", { name: "List it" }).click();
await m.getByText("Listed · waiting for interest", { exact: false }).waitFor();
await m.getByText("would like this", { exact: false }).waitFor({ timeout: 6000 });
await m.getByRole("button", { name: "Accept" }).click();
await page.getByText("Sunday's great!", { exact: false }).waitFor({ timeout: 5000 });
await page.screenshot({ path: "/tmp/shots/demo-market-chat.png" });
await page.locator(".rl-sheet").getByRole("button", { name: "Close" }).click();
await m.getByText("Deal agreed with Jordan", { exact: false }).waitFor();
assert.deepEqual(resaleCalls, [], "the demo never calls the real Market");
// Without ?demo=1 the real Market shows, with no made-up listings.
await page.goto(origin + "/index.html"); await page.waitForTimeout(800);
await page.evaluate(() => window.go("market"));
await page.waitForTimeout(1500);
assert.ok((await page.locator("#marketPage").innerText()).length > 0, "the real Market rendered");
assert.equal(await page.getByText("made-up members", { exact: false }).count(), 0, "real members never see the demo");
assert.equal(await page.getByText("Waterproof Rain Shell").count(), 0);
assert.deepEqual(errors, []);
console.log("PASS demo Market: labelled, local only, buy chat, contact details blocked, list and accept; never shown outside demo mode");
await browser.close(); server.close();
