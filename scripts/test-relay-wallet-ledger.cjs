const assert=require("node:assert/strict");
const {project}=require("../relay-wallet-ledger.js");
const a={id:"purchase-A",demo:true,customer:"Ava",item:"Retro High Trainers",detail:"UK 7",merchant:"North & Co.",price:129.99};
const b={id:"purchase-B",demo:true,customer:"Ben",item:"Other trainers",detail:"UK 9",merchant:"North & Co.",price:89.99};
const e={id:"EX-001",originalPurchaseId:"purchase-A",type:"EXCHANGE",exchange:true,customer:"Ava",store:"North & Co.",product:"Retro High Trainers",variant:"UK 8",sku:"DEMO-001",amountMinor:12999,replacementStatus:"PENDING_RETURN_RECEIPT",returnStatus:"RETURN_REQUESTED",replacementRequestId:"REQ",createdAt:"2026-10-18T12:00:00Z"};
assert.deepEqual(project({purchases:[],events:[],customer:"Ava"}),[]);
const projected=project({purchases:[a,b],events:[e],customer:"Ava"});
assert.equal(projected.length,3);
assert.equal(projected[0].status,"Replacement queued");
assert.equal(projected[0].detail,"UK 8");
assert.equal(projected[0].linkedOriginalId,a.id);
assert.equal(projected[1].status,"Exchanged");
assert.equal(projected[1].linkedReplacementId,projected[0].id);
assert.equal(projected[2].id,b.id);
assert.deepEqual(project({purchases:[b],events:[e],customer:"Ben"}),[b],"Never show another customer's exchange");
assert.equal(project({purchases:[a],events:[e],customer:"Ben"})[0].status,undefined);
assert.equal(project({purchases:[a],events:[{...e,replacementStatus:"ORDER_CREATED",returnStatus:"RETURN_RECEIVED"}],customer:"Ava"})[0].status,"Replacement ordered");
assert.deepEqual(project({purchases:[a],events:[{...e,originalPurchaseId:"nonexistent"}],customer:"Ava"}),[a],"Never show orphan replacements");
assert.deepEqual(project({purchases:[{...a,demo:false}],events:[e],customer:"Ava"}),[{...a,demo:false}],"Never project demo exchanges onto live purchases");
console.log("Relay wallet exchange projection: 9 checks passed");
