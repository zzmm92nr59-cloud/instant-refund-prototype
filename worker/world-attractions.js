const key = (s) => String(s || "").toLowerCase().normalize("NFKD").replace(/[̀-ͯ]/g, "").replace(/[’']/g, "").replace(/\s+/g, " ").trim();
// { place, attractions } for a city or area listed here, or null.
export function worldAttractionsFor(city) {
  const k = key(city);
  return W[k] ? { place: k, attractions: W[k].slice(0, 3) } : null;
}
export const WORLD_ATTRACTION_PLACES = Object.keys(W);
